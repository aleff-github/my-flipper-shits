#!/usr/bin/env python3
"""Experimental CivSwitch chat transport -> Flipper Zero BadUSB manual-assisted port.

This does not reproduce PicoSwitch's composite gamepad+keyboard USB HID device.
It only converts the already-generated payload.txt to keyboard DuckyScript, with
human-operated controller A presses and synchronized Flipper button prompts.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re

HEAD = re.compile(r"^(\d+)/(\d+)(?=\")")


def parse_payload(raw: bytes) -> list[str]:
    try:
        data = raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise ValueError("Upstream payload must be ASCII, as produced by compress.js") from exc
    # Allow original LF or CRLF, but do not modify characters within each line.
    lines = data.splitlines()
    if not lines or any(not line for line in lines):
        raise ValueError("No lines, or empty lines detected")
    if any("\r" in line or "\x00" in line for line in lines):
        raise ValueError("Unsupported embedded control character")
    n = len(lines)
    for index, line in enumerate(lines, 1):
        match = HEAD.match(line)
        if match is None or (int(match.group(1)), int(match.group(2))) != (index, n):
            raise ValueError(f"Line {index}: invalid k/N prefix (expected {index}/{n} followed by quote)")
        if len(line.encode("ascii")) + 1 > 254:
            raise ValueError(f"Line {index}: exceeds upstream 254-byte chat line limit")
        if line != line.strip():
            raise ValueError(f"Line {index}: whitespace at boundaries would be trimmed by Flipper")
        if any(ord(c) < 32 or ord(c) > 126 for c in line):
            raise ValueError(f"Line {index}: non-printable ASCII")
    return lines


def convert(lines: list[str], delay: int = 40) -> str:
    if not 20 <= delay <= 500:
        raise ValueError("Per-character delay must be between 20 and 500 ms")
    out = [
        "REM EXPERIMENTAL: CivSwitch manual-assisted keyboard transport for Flipper Zero",
        "REM NOT A CONFIRMED SWITCH/SWITCH 2 JAILBREAK. DOES NOT EMULATE GAMEPAD A.",
        "REM Follow README: at EACH WAIT press physical controller A (if prompted) and THEN Flipper Run/Resume.",
        "REM Before starting: enter Civ7 lobby/chat as in original project; use US keyboard layout.",
        f"DEFAULT_STRING_DELAY {delay}",
        "REM Before resuming: manually perform PicoSwitch initial controller A x5 preamble as needed.",
        "WAIT_FOR_BUTTON_PRESS",
    ]
    for idx, line in enumerate(lines, 1):
        out.extend([
            f"REM BATCH {idx} OF {len(lines)}: ESC, then physically press controller A, then resume Flipper",
            "ESC",
            "DELAY 800",
            "WAIT_FOR_BUTTON_PRESS",
            "DELAY 1200",
            "STRING " + line,
            "ENTER",
            "DELAY 200",
            "ENTER",
        ])
        if idx < len(lines):
            out.extend([
                "REM BETWEEN BATCHES: physically press controller A, then resume Flipper",
                "DELAY 800",
                "WAIT_FOR_BUTTON_PRESS",
                "DELAY 1200",
            ])
    out.append("REM END. Reaching this line does NOT prove exploit execution.")
    return "\n".join(out) + "\n"


def parse_ducky_strings(script: str) -> list[str]:
    """Only an offline content round-trip check, not a Flipper interpreter."""
    return [line[7:] for line in script.splitlines() if line.startswith("STRING ")]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("payload", type=Path, help="Upstream PicoSwitch/payload.txt generated by compress.js")
    p.add_argument("output", type=Path, help="Output Flipper BadUSB .txt")
    p.add_argument("--string-delay", type=int, default=40, help="Delay between typed characters in ms")
    args = p.parse_args()
    lines = parse_payload(args.payload.read_bytes())
    output = convert(lines, args.string_delay)
    if parse_ducky_strings(output) != lines:
        raise RuntimeError("Payload mismatch after conversion")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(output.encode("ascii"))
    manual_a = 5 + len(lines) + (len(lines) - 1)
    pauses = 1 + len(lines) + (len(lines) - 1)
    print(f"Validated {len(lines)} original lines, longest {max(map(len, lines))} ASCII bytes")
    print(f"DuckyScript round-trip: OK, {len(lines)} STRING, {len(lines)} ESC, {len(lines)*2} ENTER")
    print(f"Manual controller A presses expected: {manual_a} (5-preamble included)")
    print(f"Flipper resume prompts: {pauses}")
    print(f"EXPERIMENTAL output: {args.output}; no hardware or exploit verification performed")


if __name__ == "__main__":
    main()
